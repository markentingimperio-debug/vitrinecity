import assert from 'node:assert/strict';
import fs from 'node:fs';
import {toCleanPublicHref,toLegacyPublicPath} from '../public/vitriny-public-routes.js';

const page=fs.readFileSync(new URL('../public/solucoes.html',import.meta.url),'utf8');
const home=fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const server=fs.readFileSync(new URL('../server.js',import.meta.url),'utf8');
for(const expected of ['R$10 por mês','R$200 por pacote','VitrineCity Ads','Marketplace','Cursos livres','Programa de afiliados'])assert.equal(page.includes(expected),true,`conteúdo ausente: ${expected}`);
assert.match(page,/Nenhuma vaga ou oferta externa publicada no momento/);
assert.match(page,/não cria anúncios fictícios/i);
assert.match(page,/id="opportunity-form"/);
assert.match(page,/id="tracking-form"/);
assert.match(page,/id="acompanhar"/);
assert.match(page,/\/api\/opportunities/);
assert.match(page,/\/api\/opportunities\/status/);
assert.match(page,/\/api\/opportunities\/revise/);
assert.match(page,/application\/ld\+json/);
assert.match(page,/https:\/\/vitrinecity\.com\/solucoes\.html/);
assert.ok(home.includes(`href="${toCleanPublicHref('/solucoes.html')}"`),'A página inicial continua oferecendo o catálogo de serviços pelo endereço público');
assert.equal(toLegacyPublicPath('/solucoes'),'/solucoes.html','O endereço limpo usa o catálogo existente');
assert.match(server,/'\/solucoes\.html'/);
assert.match(server,/CREATE TABLE IF NOT EXISTS business_opportunities/);
assert.match(server,/app\.post\('\/api\/opportunities'/);
assert.match(server,/app\.post\('\/api\/opportunities\/status'/);
assert.match(server,/app\.post\('\/api\/opportunities\/revise'/);
assert.match(server,/app\.patch\('\/api\/admin\/opportunities\/:id'/);
assert.match(server,/notifyOpportunityDecision/);
assert.match(server,/notification_status='pending'/);
const admin=fs.readFileSync(new URL('../public/admin-oportunidades.html',import.meta.url),'utf8');
assert.match(admin,/data-status="published"/);
assert.match(admin,/data-status="changes_requested"/);
console.log('services-catalog: ok');

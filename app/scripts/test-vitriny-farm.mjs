import assert from 'node:assert/strict';
import {newFarm,restoreFarm,farmAction,farmLevel} from '../public/vitriny-farm-core.js';
let state=newFarm();const now=100000;
assert.equal(farmAction(state,{type:'plant',plot:3,crop:'carrot'},now).changed,false,'Locked land stays locked');
assert.equal(farmAction(state,{type:'plant',plot:0,crop:'corn'},now).changed,false,'Crop unlocks follow the phase');
state=farmAction(state,{type:'plant',plot:0,crop:'carrot'},now).state;assert.equal(state.coins,58);
assert.equal(farmAction(state,{type:'harvest',plot:0},now+1000).changed,false);
state=farmAction(state,{type:'water',plot:0},now+1000).state;assert.equal(state.plots[0].readyAt,now+19500);
assert.equal(farmAction(state,{type:'water',plot:0},now+2000).changed,false,'Watering bonus is applied once');
state=farmAction(state,{type:'harvest',plot:0},now+20000).state;assert.equal(state.coins,64);assert.equal(state.xp,6);
assert.equal(farmAction(state,{type:'harvest',plot:0},now+21000).changed,false,'Harvest cannot pay twice');
assert.equal(farmAction(state,{type:'feed',animal:'chicken'},now).changed,false);
state.xp=24;assert.equal(farmLevel(state),2);state=farmAction(state,{type:'feed',animal:'chicken'},now).state;assert.equal(state.coins,60);
assert.equal(farmAction(state,{type:'collect',animal:'chicken'},now+1000).changed,false);state=farmAction(state,{type:'collect',animal:'chicken'},now+45000).state;assert.equal(state.coins,70);
assert.equal(farmAction(state,{type:'collect',animal:'chicken'},now+45000).changed,false);
assert.equal(restoreFarm({version:7}),null);assert.deepEqual(restoreFarm(JSON.parse(JSON.stringify(state))),state);
state.coins=0;assert.equal(farmAction(state,{type:'plant',plot:1,crop:'carrot'},now).changed,false);
assert.equal(farmAction(state,{type:'plant',plot:1,crop:'__proto__'},now).changed,false);
console.log(JSON.stringify({ok:true,farm:'growth, care, harvest, levels, animals, local persistence, no duplicate rewards'}));

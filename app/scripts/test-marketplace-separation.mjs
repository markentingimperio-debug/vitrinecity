import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const deliveries=readFileSync(new URL('../public/entregas.html',import.meta.url),'utf8');
const shop=readFileSync(new URL('../public/loja.html',import.meta.url),'utf8');
const banner=readFileSync(new URL('../public/market-outdoor.js',import.meta.url),'utf8');
const server=readFileSync(new URL('../server.js',import.meta.url),'utf8');
const homepage=readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const city=readFileSync(new URL('../public/vitriny-multiverse-explore.html',import.meta.url),'utf8');

assert.match(deliveries,/vc-entregas-hero\.png/);
assert.match(deliveries,/Compras e entregas locais/);
assert.match(deliveries,/Loja Oficial/);
assert.match(deliveries,/delivery=local/);
assert.match(deliveries,/placeholder="Buscar loja ou restaurante"/,'The search promise matches the store-name/description query');
assert.match(deliveries,/disponibilidade de entrega é confirmada ao informar sua cidade e endereço no pedido/);
assert.match(deliveries,/Consultar entrega/);
assert.doesNotMatch(deliveries,/somente lojas da sua cidade|lojas próximas|aberta\$|\?'Aberta'|Ver produtos e comprar|outro nome ou produto/,'The catalog alone cannot guarantee local fulfillment or live store availability');
assert.match(shop,/VC Entregas — compras locais/);
assert.match(shop,/Entrega digital/);
assert.match(banner,/\/api\/marketplace\/stores\?delivery=local/);
assert.match(banner,/stores\.has\(p\.store_reference\)/);
assert.match(banner,/\/loja\?delivery=local&q=/);
assert.match(server,/delivery=String\(req\.query\.delivery/);
assert.match(server,/s\.fulfillment_mode IN \('delivery','local','both'\)/);
assert.match(homepage,/VC Entregas/);
assert.match(homepage,/Loja Oficial VitrineCity/);
const deliveryDirectory=city.match(/<dialog id="deliveryBaseDirectory"[\s\S]*?<\/dialog>/)?.[0];
assert.ok(deliveryDirectory,'The delivery building provides a destination directory');
assert.match(deliveryDirectory,/href="\/entregas"/,'Visitors can reach the real public delivery catalog');
assert.match(deliveryDirectory,/href="\/entregador\.html"/,'Couriers can reach their actual login and application form');
assert.match(deliveryDirectory,/<details><summary>Administração da base<\/summary>[\s\S]*href="\/admin-logistica\.html"[\s\S]*href="\/admin-entregas\.html"/,'Administration remains a secondary section with the existing protected destinations');
assert.ok(deliveryDirectory.indexOf('href="/entregas"')<deliveryDirectory.indexOf('<details>'));
assert.match(deliveryDirectory,/consulte as opções de entrega para sua cidade e endereço/,'The public directory directs visitors to actual address-specific availability');
console.log('marketplace separation: ok');
